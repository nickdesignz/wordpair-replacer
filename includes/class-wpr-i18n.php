class WPR_I18n {

	public static function init(): void {
		add_filter( 'gettext', array( __CLASS__, 'filter_gettext' ), 20, 3 );
	}

	public static function current_language(): string {
		$settings = WPR_Settings::get();
		$lang     = $settings['plugin_language'] ?? 'en_US';

		return in_array( $lang, array( 'en_US', 'de_DE' ), true ) ? $lang : 'en_US';
	}

	public static function translate( string $text ): string {
		$lang = self::current_language();

		if ( 'de_DE' === $lang ) {
			$map = self::german_map();

			return $map[ $text ] ?? $text;
		}

		$map = self::english_map();

		return $map[ $text ] ?? $text;
	}

	public static function filter_gettext( string $translation, string $text, string $domain ): string {
		if ( WPR_TEXTDOMAIN !== $domain ) {
			return $translation;
		}

		return self::translate( $text );
	}


